import html2canvas from 'html2canvas';
import { jsPDF } from 'jspdf';

export interface ExportPdfResult {
  blob: Blob;
  pdf: jsPDF;
  fileName: string;
}

/**
 * Renders an HTML element (styled at A4 794x1123px) to an A4 PDF using html2canvas and jsPDF.
 * Preserves Marathi (Devanagari) glyphs flawlessly via device font rendering.
 * Slices content across multiple pages with 'Page X of Y' and the statutory disclaimer footer.
 */
export interface ExportPdfOptions {
  isSample?: boolean;
  language?: string;
}

export async function exportPdf(
  element: HTMLElement,
  fileName: string = 'NyaySaathi_Document.pdf',
  options?: ExportPdfOptions
): Promise<ExportPdfResult> {
  const cleanName = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
  const isSample = options?.isSample ?? false;

  // Render element to high-res canvas (scale: 2)
  const canvas = await html2canvas(element, {
    scale: 2,
    useCORS: true,
    logging: false,
    backgroundColor: '#ffffff',
    windowWidth: element.scrollWidth || 794,
  });

  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
    compress: true,
  });

  const pdfWidth = 210; // A4 mm width
  const pdfHeight = 297; // A4 mm height

  // Height in canvas pixels corresponding to one A4 page ratio (210 x 297 mm)
  const pageCanvasHeight = Math.floor((canvas.width * pdfHeight) / pdfWidth);
  const totalPages = Math.max(1, Math.ceil(canvas.height / pageCanvasHeight));

  for (let p = 0; p < totalPages; p++) {
    if (p > 0) {
      pdf.addPage('a4', 'portrait');
    }

    const sourceY = p * pageCanvasHeight;
    const remainingHeight = canvas.height - sourceY;
    const sliceHeight = Math.min(pageCanvasHeight, remainingHeight);

    // Create a sub-canvas for the page slice
    const sliceCanvas = document.createElement('canvas');
    sliceCanvas.width = canvas.width;
    sliceCanvas.height = pageCanvasHeight;
    const ctx = sliceCanvas.getContext('2d');
    if (ctx) {
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(0, 0, sliceCanvas.width, sliceCanvas.height);
      ctx.drawImage(
        canvas,
        0,
        sourceY,
        canvas.width,
        sliceHeight,
        0,
        0,
        canvas.width,
        sliceHeight
      );
    }

    const imgData = sliceCanvas.toDataURL('image/jpeg', 0.95);
    pdf.addImage(imgData, 'JPEG', 0, 0, pdfWidth, pdfHeight);

    // If marked as sample, add clear sample watermark / note at bottom
    if (isSample) {
      pdf.setFontSize(8.5);
      pdf.setTextColor(190, 40, 40);
      pdf.text(
        '*** SAMPLE RECORD FOR DEMONSTRATION ONLY - NOT A REAL POLICE RECORD ***',
        pdfWidth / 2,
        284,
        { align: 'center' }
      );
    }

    // Page numbering and required footer line on every page
    pdf.setFontSize(8);
    pdf.setTextColor(110, 110, 110);
    pdf.text(`Page ${p + 1} of ${totalPages}`, pdfWidth / 2, 289, { align: 'center' });
    pdf.text(
      'Generated by Nyay Saathi. Decision support tool. Verify before use.',
      pdfWidth / 2,
      293,
      { align: 'center' }
    );
  }

  // Trigger browser download
  pdf.save(cleanName);

  const blob = pdf.output('blob');
  return { blob, pdf, fileName: cleanName };
}

/**
 * Triggers standard browser print dialog for printable sheets.
 */
export function printDocument(): void {
  window.print();
}

/**
 * Shares the generated PDF document using the Web Share API when supported.
 */
export async function shareDocument(
  blob: Blob,
  title: string = 'Legal Document',
  fileName: string = 'NyaySaathi_Document.pdf'
): Promise<boolean> {
  const cleanName = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
  const file = new File([blob], cleanName, { type: 'application/pdf' });

  if (
    typeof navigator !== 'undefined' &&
    typeof navigator.canShare === 'function' &&
    navigator.canShare({ files: [file] })
  ) {
    try {
      await navigator.share({
        title,
        files: [file],
      });
      return true;
    } catch (err: any) {
      if (err.name !== 'AbortError') {
        console.error('Share execution failed:', err);
      }
      return false;
    }
  }

  return false;
}
